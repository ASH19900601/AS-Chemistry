const LINES = {};
for (const k in LINES_RAW) LINES[k] = LINES_RAW[k].split('|');
for (const k in VOICE_RAW) LINES['voice_' + k] = VOICE_RAW[k].split('|');

const lineBags = {};
let lastLine = '';
function line(key, vars) {
  const pool = LINES[key];
  if (!pool) { console.warn('missing line', key); return '…'; }
  let bag = lineBags[key];
  if (!bag || !bag.length) {
    bag = pool.slice();
    for (let i = bag.length - 1; i > 0; i--) {
      const j = Math.floor(Math.random() * (i + 1));
      const t = bag[i]; bag[i] = bag[j]; bag[j] = t;
    }
    // 新的一輪不要以上一輪最後一句開頭
    if (bag.length > 1 && bag[bag.length - 1] === lineBags[key + ':last']) bag.unshift(bag.pop());
    lineBags[key] = bag;
  }
  let text = bag.pop();
  if (text === lastLine && bag.length) { bag.unshift(text); text = bag.pop(); }
  lineBags[key + ':last'] = text;
  lastLine = text;
  if (vars) for (const v in vars) text = text.split('{' + v + '}').join(vars[v]);
  return text;
}
